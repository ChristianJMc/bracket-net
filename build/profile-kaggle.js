// Profiles every CSV in raw/kaggle/csv: rows, years, columns, and a timing check against our own
// pre-tournament records (does the file's win total for a team include its tournament wins?).
// Writes docs/kaggle-profile.md.
const fs = require('fs');
const path = require('path');
const { parseCSV } = require('./lib/csv');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'raw', 'kaggle', 'csv');
const ours = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'dataset.json'), 'utf8'));
const out = ['# Kaggle "March Madness Data" profile', '', `Generated by build/profile-kaggle.js from ${fs.readdirSync(DIR).length} files.`, ''];

for (const file of fs.readdirSync(DIR).sort()) {
  const rows = parseCSV(fs.readFileSync(path.join(DIR, file), 'utf8'));
  const cols = Object.keys(rows[0] || {});
  const yearCol = cols.find(c => /^YEAR$/i.test(c));
  const years = yearCol ? [...new Set(rows.map(r => r[yearCol]))].filter(Number.isFinite).sort() : [];
  const teamCol = cols.find(c => /^TEAM$/i.test(c));
  let timing = '';
  // Timing probe: compare a wins column with our pre-tournament wins for the champion (who adds 6 tourney wins).
  const wCol = cols.find(c => /^(W|WINS)$/i.test(c));
  if (wCol && teamCol && yearCol) {
    const probes = [];
    for (const y of [2024, 2023, 2019]) {
      const champ = ours.games.find(g => g.year === y && g.round === 6);
      if (!champ) continue;
      const name = champ.sa > champ.sb ? champ.a : champ.b;
      const pre = ours.teams[y][name];
      const r = rows.find(x => x[yearCol] === y && String(x[teamCol]).replace(/\./g, '').toLowerCase() === name.replace(/\./g, '').toLowerCase());
      if (r && pre) probes.push(`${y} ${name}: file ${r[wCol]} W vs ${pre.w} pre-tourney`);
    }
    if (probes.length) timing = probes.join('; ');
  }
  out.push(`## ${file}`, '', `- Rows: ${rows.length}${years.length ? ` · years ${years[0]}–${years[years.length - 1]} (${years.length} seasons)` : ''}`);
  if (timing) out.push(`- Timing probe: ${timing}`);
  out.push(`- Columns (${cols.length}): ${cols.join(', ')}`, '');
}
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'kaggle-profile.md'), out.join('\n'));
